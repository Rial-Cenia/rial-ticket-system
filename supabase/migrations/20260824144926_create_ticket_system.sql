before update on public."Ticket"
for each row execute function public.set_updated_at();

create trigger "TicketSyncOutbox_set_updated_at"
before update on public."TicketSyncOutbox"
for each row execute function public.set_updated_at();

create or replace function public.create_ticket(
  p_title text,
  p_description text,
  p_type public."TicketType",
  p_platform public."Platform",
  p_source public."ActivitySource",
  p_actor_name text,
  p_actor_id text default null,
  p_discord_id text default null
)
returns public."Ticket"
language plpgsql
security invoker
set search_path = ''
as $$
declare
  created public."Ticket";
begin
  insert into public."Ticket" (title, description, type, platform, "createdByName", "createdByDiscordId")
  values (p_title, p_description, p_type, p_platform, p_actor_name, p_discord_id)
  returning * into created;

  insert into public."TicketActivity" ("ticketPublicId", source, action, "actorName", "actorId", changes)
  values (created."publicId", p_source, 'CREATED', p_actor_name, p_actor_id, to_jsonb(created));

  insert into public."TicketSyncOutbox" ("ticketPublicId", type, payload)
  values (created."publicId", 'CREATE_TRIAGE_THREAD', jsonb_build_object('ticketPublicId', created."publicId"));

  return created;
end;
$$;

create or replace function public.update_ticket(
  p_public_id uuid,
  p_patch jsonb,
  p_source public."ActivitySource",
  p_actor_name text,
  p_actor_id text default null
)
returns public."Ticket"
language plpgsql
security invoker
set search_path = ''
as $$
declare
  previous public."Ticket";
  changed public."Ticket";
begin
  if p_patch = '{}'::jsonb or p_patch ?| array['publicId', 'id', 'createdByName', 'createdByDiscordId', 'discordThreadId', 'createdAt', 'updatedAt'] then
    raise exception 'Invalid ticket patch';
  end if;

  select * into previous from public."Ticket" where "publicId" = p_public_id for update;
  if not found then raise exception 'Ticket not found'; end if;

  update public."Ticket"
  set
    title = case when p_patch ? 'title' then p_patch->>'title' else title end,
    description = case when p_patch ? 'description' then p_patch->>'description' else description end,
    type = case when p_patch ? 'type' then (p_patch->>'type')::public."TicketType" else type end,
    status = case when p_patch ? 'status' then (p_patch->>'status')::public."TicketStatus" else status end,
    platform = case when p_patch ? 'platform' then nullif(p_patch->>'platform', '')::public."Platform" else platform end
  where "publicId" = p_public_id
  returning * into changed;

  insert into public."TicketActivity" ("ticketPublicId", source, action, "actorName", "actorId", changes)
  values (
    p_public_id,
    p_source,
    'UPDATED',
    p_actor_name,
    p_actor_id,
    jsonb_build_object('before', to_jsonb(previous), 'after', to_jsonb(changed), 'patch', p_patch)
  );

  if p_source = 'WEB' and changed."discordThreadId" is not null then
    insert into public."TicketSyncOutbox" ("ticketPublicId", type, payload)
    values (
      p_public_id,
      'SEND_THREAD_MESSAGE',
      jsonb_build_object(
        'threadId', changed."discordThreadId",
        'content', format('%s El ticket fue actualizado por **%s**.%s%s',
          case when p_source = 'WEB' then '🔄 Desde el tablero Kanban Web.' else '📝 Desde Discord.' end,
          p_actor_name,
          case when p_patch ? 'status' then format(E'\nEstado: **%s**', changed.status) else '' end,
          case when p_patch ? 'platform' then format(E'\nPlataforma: **%s**', coalesce(changed.platform::text, 'Sin asignar')) else '' end
        )
      )
    );
  end if;

  return changed;
end;
$$;

create or replace function public.delete_ticket(
  p_public_id uuid,
  p_source public."ActivitySource",
  p_actor_name text,
  p_actor_id text default null
)
returns public."Ticket"
language plpgsql
security invoker
set search_path = ''
as $$
declare
  removed public."Ticket";
begin
  select * into removed from public."Ticket" where "publicId" = p_public_id for update;
  if not found then raise exception 'Ticket not found'; end if;

  insert into public."TicketActivity" ("ticketPublicId", source, action, "actorName", "actorId", changes)
  values (p_public_id, p_source, 'DELETED', p_actor_name, p_actor_id, jsonb_build_object('ticket', to_jsonb(removed)));

  if removed."discordThreadId" is not null then
    insert into public."TicketSyncOutbox" ("ticketPublicId", type, payload)
    values (
      p_public_id,
      'ARCHIVE_THREAD',
      jsonb_build_object('threadId', removed."discordThreadId", 'content', format('🗑️ Ticket eliminado desde la web por **%s**.', p_actor_name))
    );
  end if;

  delete from public."Ticket" where "publicId" = p_public_id;
  return removed;
end;
$$;

