create or replace function public.set_ticket_discord_thread(p_public_id uuid, p_thread_id text)
returns public."Ticket"
language plpgsql
security invoker
set search_path = ''
as $$
declare changed public."Ticket";
begin
  update public."Ticket" set "discordThreadId" = p_thread_id where "publicId" = p_public_id returning * into changed;
  if not found then raise exception 'Ticket not found'; end if;
  return changed;
end;
$$;

create or replace function public.claim_ticket_sync_jobs(p_limit integer default 10)
returns setof public."TicketSyncOutbox"
language sql
security invoker
set search_path = ''
as $$
  with due as (
    select id from public."TicketSyncOutbox"
    where (status = 'PENDING' or (status = 'PROCESSING' and "lockedAt" < now() - interval '10 minutes'))
      and "nextAttemptAt" <= now()
      and attempts < 8
    order by "createdAt"
    for update skip locked
    limit greatest(1, least(p_limit, 50))
  )
  update public."TicketSyncOutbox" jobs
  set status = 'PROCESSING', "lockedAt" = now(), attempts = attempts + 1
  from due
  where jobs.id = due.id
  returning jobs.*;
$$;

create or replace function public.complete_ticket_sync_job(p_id uuid)
returns void
language sql
security invoker
set search_path = ''
as $$
  update public."TicketSyncOutbox"
  set status = 'DELIVERED', "deliveredAt" = now(), "lockedAt" = null, "lastError" = null
  where id = p_id;
$$;

create or replace function public.retry_ticket_sync_job(
  p_id uuid,
  p_error text,
  p_retry_after_seconds integer default null,
  p_permanent boolean default false
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare current_attempts integer;
begin
  select attempts into current_attempts from public."TicketSyncOutbox" where id = p_id for update;
  update public."TicketSyncOutbox"
  set
    status = case when p_permanent or current_attempts >= 8 then 'DEAD_LETTER'::public."OutboxStatus" else 'PENDING'::public."OutboxStatus" end,
    "lastError" = left(p_error, 1000),
    "lockedAt" = null,
    "nextAttemptAt" = now() + make_interval(secs => coalesce(p_retry_after_seconds, least(3600, power(2, current_attempts)::integer * 30)))
  where id = p_id;
end;
$$;

