create extension if not exists pgcrypto;
create extension if not exists pg_cron;
create extension if not exists pg_net;

create type public."TicketType" as enum ('REQUERIMIENTO', 'MEJORA', 'DUDA', 'BUG');
create type public."TicketStatus" as enum ('PENDIENTE', 'EN_PROGRESO', 'EN_ESPERA', 'RESUELTO');
create type public."Platform" as enum ('NESTOR', 'DYLAN', 'ATOM', 'KAYS');
create type public."ActivitySource" as enum ('WEB', 'DISCORD');
create type public."OutboxJobType" as enum ('CREATE_TRIAGE_THREAD', 'SEND_THREAD_MESSAGE', 'ARCHIVE_THREAD');
create type public."OutboxStatus" as enum ('PENDING', 'PROCESSING', 'DELIVERED', 'DEAD_LETTER');

create table public."Ticket" (
  id bigint generated by default as identity primary key,
  "publicId" uuid not null default gen_random_uuid() unique,
  title text not null check (char_length(title) between 1 and 200),
  description text not null check (char_length(description) between 1 and 4000),
  type public."TicketType" not null default 'REQUERIMIENTO',
  status public."TicketStatus" not null default 'PENDIENTE',
  platform public."Platform",
  "createdByName" text not null,
  "createdByDiscordId" text,
  "discordThreadId" text unique,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table public."TicketActivity" (
  id bigint generated always as identity primary key,
  "ticketPublicId" uuid not null,
  source public."ActivitySource" not null,
  action text not null,
  "actorName" text not null,
  "actorId" text,
  changes jsonb not null default '{}'::jsonb,
  "createdAt" timestamptz not null default now()
);

create table public."TicketSyncOutbox" (
  id uuid primary key default gen_random_uuid(),
  "ticketPublicId" uuid not null,
  type public."OutboxJobType" not null,
  payload jsonb not null default '{}'::jsonb,
  status public."OutboxStatus" not null default 'PENDING',
  attempts integer not null default 0 check (attempts between 0 and 8),
  "nextAttemptAt" timestamptz not null default now(),
  "lastError" text,
  "lockedAt" timestamptz,
  "deliveredAt" timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table public."DiscordInteraction" (
  id text primary key,
  type integer not null,
  "createdAt" timestamptz not null default now()
);

create index "Ticket_status_idx" on public."Ticket" (status);
create index "Ticket_platform_idx" on public."Ticket" (platform);
create index "Ticket_type_idx" on public."Ticket" (type);
create index "Ticket_updatedAt_idx" on public."Ticket" ("updatedAt" desc);
create index "TicketActivity_ticketPublicId_idx" on public."TicketActivity" ("ticketPublicId", "createdAt" desc);
create index "TicketSyncOutbox_due_idx" on public."TicketSyncOutbox" (status, "nextAttemptAt");

alter table public."Ticket" replica identity full;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new."updatedAt" = now();
  return new;
end;
$$;

